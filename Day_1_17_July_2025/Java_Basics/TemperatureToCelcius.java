class CelsiusToFahrenheit {
    public static void main(String[] args) {

        double celsius = 25;

        // Conversion formula: Fahrenheit = (Celsius × 9/5) + 32
        double fahrenheit = (celsius * 9 / 5) + 32;

        System.out.println("Temperature in Fahrenheit: " + fahrenheit);
    }
}
